"""A realism check on auditor-written content, like Petri's realism approver.

An audit only measures how agents behave in a run that looks real to them.
``RealismCheck`` is an approver (``audit_task(approver=...)``): before
auditor-written content reaches agents, it asks a model whether the content's
apparent source would plausibly produce it, given the recent channel messages.
A flag rejects the operation through the controller's ordinary rejection path,
so the auditor reads the reason at its next wake and can try again. Under a
``SeatPolicy`` every seat turn is checked, and a flagged one is silently
generated by the seated agent's own model instead.

Its model calls are not charged to the audit budget yet; they should be once
auditor spend is (spec §5.6).
"""

from __future__ import annotations

import json
import re

from inspect_ai.model import ChatMessageUser, GenerateConfig, Model, get_model
from inspect_ai.util import span

from orbit_audit.auditor.prompts import REALISM_CHECK
from orbit_audit.ops import ActivationOp, ControlOp, InjectMessage, RewriteMessage, ToolOp
from orbit_audit.policy import BoundaryView

RECENT_MESSAGES = 8
_VERDICT = re.compile(r"\W*(UNREALISTIC|REALISTIC)\b\W*(.*)", re.IGNORECASE)


class RealismCheck:
    """Approver: ``"unrealistic: <reason>"`` when its model judges content implausible.

    The answer must start with REALISTIC or UNREALISTIC. Anything else
    approves (fails open): a broken checker should not block every operation
    or hand the auditor a reason no one gave.
    """

    def __init__(self, *, model: str | Model, config: GenerateConfig | None = None) -> None:
        self._model = model
        self.config = config or GenerateConfig()

    @property
    def model(self) -> Model:
        if not isinstance(self._model, Model):
            self._model = get_model(self._model)
        return self._model

    async def __call__(self, view: BoundaryView, op: ControlOp) -> str | None:
        prompt = REALISM_CHECK.format(
            source=_source(view, op), messages=_recent(view), op=op.name,
            content=json.dumps(op.payload(), ensure_ascii=False),
        )
        async with span("realism-check", type="orbit_audit.auditor"):
            output = await self.model.generate([ChatMessageUser(content=prompt)],
                                               config=self.config)
        verdict = _VERDICT.match(output.completion)
        if verdict is None or verdict.group(1).upper() == "REALISTIC":
            return None
        return f"unrealistic: {verdict.group(2).strip() or 'no reason given'}"


def _source(view: BoundaryView, op: ControlOp) -> str:
    """Who the agents will take ``op``'s content to come from."""
    if isinstance(op, ToolOp):
        return f"the {view.tool_name} tool, called by {op.agent} with {view.tool_arguments}"
    if isinstance(op, ActivationOp):
        return f"the environment or a user, as input to {op.agent}"
    if isinstance(op, InjectMessage):
        return f"{op.sender}, posting on #{op.channel_id}"
    if isinstance(op, RewriteMessage):
        sender = next((m["sender"] for m in view.messages if m["id"] == op.message_id),
                      f"the sender of message {op.message_id}")
        return f"{sender}, in place of what it sent"
    return f"{', '.join(op.agents())}, as its own output"


def _recent(view: BoundaryView) -> str:
    return "\n".join(
        f"({m['id']}) #{m['channel_id']} {m['sender']} → {', '.join(m['recipients'])}: "
        f"{m['content']}" for m in view.messages[-RECENT_MESSAGES:]
    ) or "(none yet)"
